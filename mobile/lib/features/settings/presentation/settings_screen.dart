class _AppearanceSection extends ConsumerWidget {
  const _AppearanceSection();

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final mode = ref.watch(appearanceProvider);
    return CourtCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionLabel('Appearance'),
          const SizedBox(height: 14),
          SizedBox(
            width: double.infinity,
            child: SegmentedButton<ThemeMode>(
              key: const Key('appearance'),
              showSelectedIcon: false,
              // Material's default selected fill is the scheme's secondary,
              // which here is the verdict green — a colour that means "not
              // guilty" everywhere else in the app. Use the yellow the nav
              // pill uses for "this is the one you are on".
              style: SegmentedButton.styleFrom(
                selectedBackgroundColor: CourtColors.yellow,
                selectedForegroundColor: CourtColors.lightInk,
                foregroundColor: context.colors.onSurface,
                side: BorderSide(
                  color: context.palette.border,
                  width: courtBorderThin,
                ),
                // styleFrom replaces the text style outright, so the family
                // has to be named again — without it the segments set in the
                // platform default rather than the canvas's one typeface.
                textStyle: const TextStyle(
                  fontFamily: courtBodyFont,
                  fontWeight: FontWeight.w800,
                  fontSize: 14,
                ),
              ),
              segments: const [
                ButtonSegment(value: ThemeMode.light, label: Text('Light')),
                ButtonSegment(value: ThemeMode.dark, label: Text('Dark')),
                ButtonSegment(value: ThemeMode.system, label: Text('System')),
              ],
              selected: {mode},
              onSelectionChanged: (selection) =>
                  ref.read(appearanceProvider.notifier).set(selection.first),
            ),
          ),
          const SizedBox(height: 10),
          Text(
            'The courtroom is a bright design, so light is the default. Dark '
            'is there if you prefer it.',
            style: context.text.bodySmall?.copyWith(
              color: context.palette.inkDim,
            ),
          ),
        ],
      ),
    );
  }
}

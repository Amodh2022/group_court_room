class SettingsScreen extends ConsumerWidget {
  const SettingsScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final session = ref.watch(authControllerProvider).valueOrNull;

    return CourtScaffold(
      title: 'Settings',
      tab: CourtTab.settings,
      body: ListView(
        padding: const EdgeInsets.fromLTRB(16, 12, 16, 40),
        children: [
          CourtCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const SectionLabel('Signed in as'),
                const SizedBox(height: 8),
                Text(
                  session?.displayName ?? 'Not signed in',
                  style: context.text.titleLarge,
                ),
                const SizedBox(height: 16),
                OutlinedButton.icon(
                  onPressed: () async {
                    await ref.read(authControllerProvider.notifier).signOut();
                    if (context.mounted) context.go('/sign-in');
                  },
                  icon: const Icon(Icons.logout),
                  label: const Text('Sign out'),
                ),
              ],
            ),
          ),
          const SizedBox(height: 16),
          const _AppearanceSection(),
          const SizedBox(height: 16),
          const _PrivacySection(),
          const SizedBox(height: 16),
          CourtCard(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                const SectionLabel('About'),
                const SizedBox(height: 10),
                _Fact(label: 'Version', value: '0.1.0 (private beta)'),
                _Fact(label: 'Court API', value: Env.apiBaseUrl),
                const SizedBox(height: 12),
                Text(
                  'Group Chat Court is entertainment. Verdicts are generated by '
                  'a language model from two unverified accounts, and establish '
                  'nothing about what actually happened. They are not legal '
                  'advice and not a dispute-resolution service.',
                  style: context.text.bodySmall?.copyWith(
                    color: context.palette.inkDim,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}

class _PrivacySection extends StatelessWidget {
  const _PrivacySection();

  static const _points = <(IconData, String, String)>[
    (
      Icons.visibility_off_outlined,
      'Nothing is public by default',
      'A verdict is private to you until you explicitly publish it. Publishing '
          'is one tap, and so is revoking.',
    ),
    (
      Icons.shield_outlined,
      'Two separate links',
      'The summons link and the public verdict link are different capabilities. '
          'Revoking one never affects the other.',
    ),
    (
      Icons.description_outlined,
      'Submissions stay private',
      'A published page shows the judge’s write-up only — never the raw '
          'accusation or the raw defense.',
    ),
    (
      Icons.delete_outline,
      'Deleting means deleting',
      'Dismissing a case removes it and kills every link you have shared, '
          'immediately.',
    ),
    (
      Icons.block,
      'Not for serious matters',
      'The court declines to joke about anything genuinely serious, and routes '
          'it to a straight answer instead.',
    ),
  ];

  @override
  Widget build(BuildContext context) => CourtCard(
    child: Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const SectionLabel('Privacy'),
        const SizedBox(height: 14),
        for (final (icon, title, body) in _points)
          Padding(
            padding: const EdgeInsets.only(bottom: 18),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Icon(icon, size: 20, color: context.palette.accent),
                const SizedBox(width: 12),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        title,
                        style: context.text.titleSmall?.copyWith(
                          fontWeight: FontWeight.w700,
                        ),
                      ),
                      const SizedBox(height: 4),
                      Text(
                        body,
                        style: context.text.bodySmall?.copyWith(
                          color: context.palette.inkDim,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),
      ],
    ),
  );
}

class _Fact extends StatelessWidget {
  const _Fact({required this.label, required this.value});

  final String label;
  final String value;

  @override
  Widget build(BuildContext context) => Padding(
    padding: const EdgeInsets.only(bottom: 8),
    child: Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        SizedBox(
          width: 92,
          child: Text(
            label,
            style: context.text.bodySmall?.copyWith(
              color: context.palette.inkDim,
            ),
          ),
        ),
        Expanded(child: Text(value, style: context.text.bodySmall)),
      ],
    ),
  );
}

class _AppearanceSection extends ConsumerWidget {
  const _AppearanceSection();

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final mode = ref.watch(appearanceProvider);
    return CourtCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SectionLabel('Appearance'),
          const SizedBox(height: 14),
          SizedBox(
            width: double.infinity,
            child: SegmentedButton<ThemeMode>(
              key: const Key('appearance'),
              showSelectedIcon: false,
              segments: const [
                ButtonSegment(value: ThemeMode.light, label: Text('Light')),
                ButtonSegment(value: ThemeMode.dark, label: Text('Dark')),
                ButtonSegment(value: ThemeMode.system, label: Text('System')),
              ],
              selected: {mode},
              onSelectionChanged: (selection) =>
                  ref.read(appearanceProvider.notifier).set(selection.first),
            ),
          ),
          const SizedBox(height: 10),
          Text(
            'The courtroom is a bright design, so light is the default. Dark '
            'is there if you prefer it.',
            style: context.text.bodySmall?.copyWith(
              color: context.palette.inkDim,
            ),
          ),
        ],
      ),
    );
  }
}

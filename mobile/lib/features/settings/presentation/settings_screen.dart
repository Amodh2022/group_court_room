class SettingsScreen extends ConsumerWidget {
  const SettingsScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final session = ref.watch(authControllerProvider).valueOrNull;

    final cards = <Widget>[
      _AccountCard(session: session),
      const _AppearanceSection(),
      const _PrivacySection(),
      const _AboutCard(),
    ];

    return CourtScaffold(
      title: 'Settings',
      // The tablet artboard opens the profile with a greeting and sets the
      // cards in two columns inside the canvas's 28px page.
      tablet: SueTabletPage(
        header: SueTabletHeader(
          title: session == null ? 'Profile' : 'Hi, ${session.displayName}',
          subtitle: 'Settings',
        ),
        child: ListView(
          padding: EdgeInsets.zero,
          children: [
            SueColumns(
              start: cards.take(2).toList(),
              end: cards.skip(2).toList(),
            ),
          ],
        ),
      ),
      header: ScreenHeader(
        title: 'Settings',
        eyebrow: session?.displayName.toUpperCase(),
        titleSize: 32,
        padding: const EdgeInsets.fromLTRB(20, 20, 20, 12),
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(16, 0, 16, courtNavBottomInset),
        children: [
          for (var i = 0; i < cards.length; i++) ...[
            if (i > 0) const SizedBox(height: 16),
            cards[i],
          ],
        ],
      ),
    );
  }
}

/// "Signed in as", and the way out.
class _AccountCard extends ConsumerWidget {
  const _AccountCard({required this.session});

  final Session? session;

  @override
  Widget build(BuildContext context, WidgetRef ref) => CourtCard(
    child: Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const SectionLabel('Signed in as'),
        const SizedBox(height: 8),
        Text(
          session?.displayName ?? 'Not signed in',
          style: context.text.titleLarge,
        ),
        const SizedBox(height: 16),
        CourtKey(
          label: 'Sign out',
          glyph: CourtGlyph.close,
          height: 52,
          fill: context.colors.surfaceContainerHighest,
          foreground: context.colors.onSurface,
          shadowInk: context.palette.shadowInk,
          onPressed: () async {
            await ref.read(authControllerProvider.notifier).signOut();
            if (context.mounted) context.go('/sign-in');
          },
        ),
      ],
    ),
  );
}

